def load(*names):
    for n in names:
        p = ROOT / n
        if p.exists():
            return json.loads(p.read_text()), n
    return None, None


def commit():
    try:
        return subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True).stdout.strip()
    except Exception:
        return "unknown"


